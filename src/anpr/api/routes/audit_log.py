"""The signed audit log: read with filters, verify the chain, record exports.

Reading needs audit.read (admins, auditors). Every entry is already free of secrets and full
plates (writers mask them), so entries are returned as stored, with their hash links and
signatures so anyone can re-verify them offline with the public key (GET /audit/public-key).
Exports are generated by the client from what it read; POST /audit/exports records that an
export happened, in the log itself.
"""

from datetime import datetime
from typing import Annotated

from fastapi import APIRouter, Depends, Query, Request
from sqlalchemy import select

from anpr.api import schemas
from anpr.api.deps import Db, audit, rate_limit, require
from anpr.db.models import AuditEntry
from anpr.security import audit_chain
from anpr.security.keys import public_key_b64
from anpr.security.rbac import Actor

router = APIRouter(prefix="/audit", tags=["audit"], dependencies=[Depends(rate_limit("audit", "camera_rate_per_minute"))])
AuditRead = Annotated[Actor, Depends(require("audit.read"))]
AuditVerify = Annotated[Actor, Depends(require("audit.verify"))]
AuditExport = Annotated[Actor, Depends(require("audit.export"))]


@router.get("", response_model=list[schemas.AuditOut], summary="Audit entries, newest first, with optional filters")
def list_entries(actor: AuditRead, db: Db,
                 action: Annotated[str | None, Query(max_length=64)] = None,
                 actor_id: Annotated[str | None, Query(max_length=64)] = None,
                 target_id: Annotated[str | None, Query(max_length=64)] = None,
                 since: datetime | None = None, until: datetime | None = None,
                 before_seq: Annotated[int | None, Query(ge=1)] = None,
                 limit: Annotated[int, Query(ge=1, le=1000)] = 200):
    stmt = select(AuditEntry)
    if action:
        # "auth." matches every auth action; a full name matches exactly
        stmt = stmt.where(AuditEntry.action.startswith(action, autoescape=True) if action.endswith(".") else AuditEntry.action == action)
    if actor_id:
        stmt = stmt.where(AuditEntry.actor_id == actor_id)
    if target_id:
        stmt = stmt.where(AuditEntry.target_id == target_id)
    if since:
        stmt = stmt.where(AuditEntry.ts >= since)
    if until:
        stmt = stmt.where(AuditEntry.ts <= until)
    if before_seq:
        stmt = stmt.where(AuditEntry.seq < before_seq)
    return db.scalars(stmt.order_by(AuditEntry.seq.desc()).limit(limit)).all()


@router.get("/verify", response_model=schemas.IntegrityOut, summary="Walk the whole chain: hash links and Ed25519 signatures")
def verify(request: Request, actor: AuditVerify, db: Db):
    result = audit_chain.verify(db, request.app.state.keys.audit_signing_key().public_key())
    return schemas.IntegrityOut(ok=result.ok, entries=result.entries, first_bad_seq=result.first_bad_seq, reason=result.reason)


@router.get("/public-key", summary="Ed25519 public key that verifies every entry's signature (base64, raw 32 bytes)")
def public_key(request: Request, actor: AuditRead):
    return {"algorithm": "Ed25519", "publicKey": public_key_b64(request.app.state.keys.audit_signing_key().public_key())}


@router.post("/exports", status_code=204, summary="Record that the caller exported audit entries")
def record_export(body: schemas.AuditExportIn, request: Request, actor: AuditExport, db: Db):
    audit(request, db, actor, "audit.export", "audit", None, justification=f"rows={body.rows} filters={body.filters[:200]}")
    db.commit()
